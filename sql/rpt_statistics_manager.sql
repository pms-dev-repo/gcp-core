create table if not exists public.rpt_statistics_manager (
  statistics_manager_id bigint generated by default as identity primary key,
  business_date date not null,
  property text not null,
  arrival_rooms integer not null,
  departure_rooms integer not null,
  individual_rooms integer not null,
  group_rooms integer not null,
  no_show_rooms integer not null,
  cancel_rooms integer not null,
  walk_in_rooms integer not null,
  house_use_rooms integer not null,
  day_use_rooms integer not null,
  complimentary_rooms integer not null,
  extended_stay_rooms integer not null,
  occupancy_pct numeric,
  occupancy_pct_minus_complimentary_house_use numeric,
  occupancy_pct_minus_complimentary_house_use_out_of_order numeric,
  occupied_rooms integer not null,
  out_of_order_rooms integer not null,
  room_revenue numeric,
  fb_revenue numeric,
  other_revenue numeric,
  total_revenue numeric,
  room_tax numeric,
  fb_tax numeric,
  other_tax numeric,
  total_tax numeric,
  source_file text,
  loaded_at timestamptz not null default now(),
  unique (property, business_date)
);
